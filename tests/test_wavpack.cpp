// --- hybrid stream writer --------------------------------------------------
// Mono 16-bit hybrid block, no decorrelation, constant error limit: every
// residual is coded in the first median band (one unary '0' covers two
// samples), then narrowed by bisection to within the limit, then a sign bit.
struct BitWriter {
  std::vector<uint8_t> bytes;
  int used = 8;
  void bit(int b) {
    if (used == 8) bytes.push_back(0), used = 0;
    if (b) bytes.back() = static_cast<uint8_t>(bytes.back() | (1u << used));
    ++used;
  }
};

void put16(std::vector<uint8_t>& v, uint32_t x) {
  v.push_back(static_cast<uint8_t>(x));
  v.push_back(static_cast<uint8_t>(x >> 8));
}
void put32(std::vector<uint8_t>& v, uint32_t x) {
  put16(v, x & 0xffff);
  put16(v, x >> 16);
}
void meta(std::vector<uint8_t>& v, int id, const std::vector<uint8_t>& d) {
  std::vector<uint8_t> body = d;
  bool odd = body.size() & 1;
  if (odd) body.push_back(0);
  size_t words = body.size() / 2;
  int flags = (odd ? 0x40 : 0) | (words > 255 ? 0x80 : 0);
  v.push_back(static_cast<uint8_t>(id | flags));
  v.push_back(static_cast<uint8_t>(words));
  if (words > 255) put16(v, static_cast<uint32_t>(words >> 8));
  v.insert(v.end(), body.begin(), body.end());
}

struct HybridFixture {
  std::vector<uint8_t> file;
  std::vector<int32_t> expect;  // what a decoder must reconstruct
};

HybridFixture makeHybrid(int frames, const std::vector<int32_t>& wanted) {
  const uint32_t errorLimit = 4;  // = 2^(0x300/256 - 1): bitrate accumulator 0x0300
  uint32_t median = 2048;         // = 2^(0xc00/256 - 1)
  HybridFixture fx;
  BitWriter bw;
  uint32_t crc = 0xffffffffu;
  for (int i = 0; i < frames; ++i) {
    if (!(i & 1)) bw.bit(0);  // ones = 0 for this sample and the next (held zero)
    uint32_t low = 0, high = (median >> 4);  // band 0: [0, med0 - 1], med0 = (m >> 4) + 1
    median -= ((median + 126) / 128) * 2;
    int32_t w = wanted[static_cast<size_t>(i)];
    uint32_t mag = static_cast<uint32_t>(w < 0 ? ~w : w);
    mag = std::min(mag, high);
    uint32_t mid = (high + low + 1) >> 1;
    while (high - low > errorLimit) {
      int b = mag >= mid;
      bw.bit(b);
      if (b)
        low = mid;
      else
        high = mid - 1;
      mid = (high + low + 1) >> 1;
    }
    bw.bit(w < 0);
    int32_t got = w < 0 ? static_cast<int32_t>(~mid) : static_cast<int32_t>(mid);
    fx.expect.push_back(got);
    crc = crc * 3 + static_cast<uint32_t>(got);
  }
  std::vector<uint8_t> body;
  meta(body, 0x2, {});                                // no decorrelation passes
  meta(body, 0x5, {0x00, 0x0c, 0x00, 0x0c, 0x00, 0x0c});  // medians 2048
  meta(body, 0x6, {0x00, 0x03});                      // bitrate accumulator
  meta(body, 0xa, bw.bytes);
  const uint32_t flags = 1u | 4u | 8u | 0x800u | 0x1000u | (9u << 23);  // 16-bit mono hybrid, 44.1 kHz
  std::vector<uint8_t>& f = fx.file;
  f = {'w', 'v', 'p', 'k'};
  put32(f, static_cast<uint32_t>(24 + body.size()));
  put16(f, 0x407);
  f.push_back(0), f.push_back(0);
  put32(f, static_cast<uint32_t>(frames));
  put32(f, 0);
  put32(f, static_cast<uint32_t>(frames));
  put32(f, flags);
  put32(f, crc);
  f.insert(f.end(), body.begin(), body.end());
  return fx;
}

std::vector<uint8_t> readFile(const std::string& p) {
  std::ifstream in(p, std::ios::binary);
  return std::vector<uint8_t>((std::istreambuf_iterator<char>(in)), {});
}

// Total frames announced by the block headers (first block of each group).
uint64_t headerFrames(const std::vector<uint8_t>& b) {
  uint64_t total = 0;
  size_t pos = 0;
  auto le32 = [&](size_t o) {
    return static_cast<uint32_t>(b[o] | b[o + 1] << 8 | b[o + 2] << 16) | static_cast<uint32_t>(b[o + 3]) << 24;
  };
  while (pos + 32 <= b.size() && !std::memcmp(&b[pos], "wvpk", 4)) {
    if (le32(pos + 24) & 0x800) total += le32(pos + 20);
    pos += 8 + le32(pos + 4);
  }
  return total;
}

