// K-14: the application icon built into the program, and the names that tie the running window
// to its desktop entry. No SDL here (unit tested); AppIcon.h applies it to SDL windows.
#pragma once
#include <cstddef>
#include <cstdint>
#include <vector>

namespace gl::appicon {

// The desktop entry id (assets/linux/gridline.desktop without ".desktop"). The X11 WM_CLASS,
// the Wayland app_id and the desktop entry's StartupWMClass all carry it, so panels, docks and
// window switchers match the window to the launcher and show its icon. The icon name
// (hicolor/<size>/apps/gridline.png, scalable/apps/gridline.svg) is the same word.
constexpr const char* kDesktopId = "gridline";
constexpr const char* kIconName = "gridline";
// The macOS bundle identifier (and the AppStream component id up to 0.7.1).
constexpr const char* kAppId = "org.gridline.Gridline";
// K-1: the AppStream component id (assets/linux/com.lolitemaultes.Gridline.metainfo.xml),
// which is also the Flatpak application id; the metainfo lists kAppId as the id it replaces.
// Inside the Flatpak the desktop entry, icon and window class are renamed to it (packaging/flatpak).
constexpr const char* kAppStreamId = "com.lolitemaultes.Gridline";

struct EmbeddedPng {
  int size;
  const unsigned char* data;
  std::size_t bytes;
};
// Generated by cmake/EmbedAppIcon.cmake from assets/icons/gridline-app-<size>.png.
const EmbeddedPng* embeddedPngs(int* count);

struct Image {
  int w = 0, h = 0;
  std::vector<std::uint8_t> rgba;  // w * h * 4, straight alpha
};
// The embedded icon closest to `size` (the smallest one at least that big, else the largest),
// decoded. Empty when nothing is embedded or decoding failed.
Image decode(int size);

}  // namespace gl::appicon
